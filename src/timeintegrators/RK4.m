function U = RK4(U,flux,lam,gamma,dx,dt,kappa,rec,CD_Term_Order,riemann_solver,xs,time)
% 4th order Runge-Kutta (custom coefficients)
k0 = dt*computeFluxDerivative(U,flux,lam,gamma,dx,kappa,rec,CD_Term_Order,riemann_solver,xs,time);
k1 = U + 0.5*dt*computeFluxDerivative(U,flux,lam,gamma,dx,kappa,rec,CD_Term_Order,riemann_solver,xs,time);
k2 = (649/1600)*U - (10890423/25193600)*k0 + (951/1600)*k1 + ...
     (5000/7873)*dt*computeFluxDerivative(k1,flux,lam,gamma,dx,kappa,rec,CD_Term_Order,riemann_solver,xs,time);
k3 = (53989/2500000)*U - (102261/5000000)*k0 + (4806213/20000000)*k1 ...
     - (5121/20000)*dt*computeFluxDerivative(k1,flux,lam,gamma,dx,kappa,rec,CD_Term_Order,riemann_solver,xs,time) + ...
     (23619/32000)*k2 + ...
     (7873/10000)*dt*computeFluxDerivative(k2,flux,lam,gamma,dx,kappa,rec,CD_Term_Order,riemann_solver,xs,time);
U = (1/5)*U + (1/10)*k0 + (6127/30000)*k1 + ...
    (1/6)*dt*computeFluxDerivative(k1,flux,lam,gamma,dx,kappa,rec,CD_Term_Order,riemann_solver,xs,time) + ...
    (7873/30000)*k2 + (1/3)*k3 + ...
    (1/6)*dt*computeFluxDerivative(k3,flux,lam,gamma,dx,kappa,rec,CD_Term_Order,riemann_solver,xs,time);
end
